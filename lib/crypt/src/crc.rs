pub fn get_biovideo_crc(file_content: &[u8; 0x20000]) -> [u8; 2] {
    // The first two bytes of the file content are the CRC
    return [file_content[0], file_content[1]];
}

pub fn compute_biovideo_crc(file_content: &[u8; 0x20000]) -> [u8; 2] {
    // The CRC is computed over the file content starting from byte 2 (i.e. excluding the first two bytes which are the CRC)
    let file_content = &mut file_content.to_owned();
    apply_xor_layer(file_content);
    compute_crc(&file_content[2..])
}

pub fn compute_crc(data: &[u8]) -> [u8; 2] {
    let mut crc: [u8; 2] = [0xff, 0xff];

    for &byte in data {
        let crc_table_index = (crc[0] ^ byte) as usize * 2;
        crc[0] = crc[1] ^ CRC_TABLE[crc_table_index + 1];
        crc[1] = CRC_TABLE[crc_table_index];
    }

    [!crc[1], !crc[0]]
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn test_get_crc() {
        let input =
            fs::read("./assets/biovideo_decrypted.bin").expect("Failed to read decrypted video");
        let crc = [0x75, 0xd8];
        let file_crc = get_biovideo_crc(
            &input
                .try_into()
                .expect("Input file should be exactly 0x20000 bytes"),
        );
        assert_eq!(
            crc, file_crc,
            "CRC read from file does not match expected value"
        );
    }

    #[test]
    fn test_crc() {
        let input =
            fs::read("./assets/biovideo_decrypted.bin").expect("Failed to read decrypted video");
        let crc = [0x75, 0xd8];
        let computed_crc = compute_biovideo_crc(
            &input
                .try_into()
                .expect("Input file should be exactly 0x20000 bytes"),
        );
        assert_eq!(crc, computed_crc, "CRC does not match expected value");
    }
}
