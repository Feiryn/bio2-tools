pub struct BiovideoEncryptionFiles {
    pub bio2base: [u8; 0x20000],
    pub firmware: [u8; 0x10000],
}

fn crypt_biovideo_inner(file_content: &[u8; 0x20000]) -> [u8; 0x20000] {
    let mut result = vec![0xffu8; 0x20000];

    let mut curr_key = [
        0x0b, 0xcb, 0x44, 0x5d, 0xac, 0x1a, 0x27, 0xb4, 0x98, 0x73, 0xbc, 0xf8, 0x6b, 0x00, 0x00,
        0x00,
    ];

    let mut i = 0xfc0000;
    while i < 0xfe0000 {
        curr_key[13] = ((i >> 16) & 0xff) as u8;
        curr_key[14] = ((i >> 8) & 0xff) as u8;
        curr_key[15] = (i & 0xff) as u8;

        let crypted_block = crypt_16_bytes(&curr_key);

        let crypted_file_bytes = file_content
            [(i - 0xfc0000) as usize..(i - 0xfc0000 + 16) as usize]
            .iter()
            .zip(crypted_block.iter())
            .map(|(r_byte, d_byte)| *r_byte ^ *d_byte)
            .collect::<Vec<u8>>();

        result[(i - 0xfc0000) as usize..(i - 0xfc0000 + 16) as usize]
            .copy_from_slice(&crypted_file_bytes);

        i += 16;
    }

    result
        .try_into()
        .expect("Result vector should be exactly 0x20000 bytes")
}

pub fn encrypt_biovideo(files: BiovideoEncryptionFiles) -> [u8; 0x20000] {
    let mut buf: [u8; 0x20000] = files.bio2base.to_owned();

    buf[0x10000..0x20000].copy_from_slice(&files.firmware);
    apply_xor_layer(&mut buf);

    crypt_biovideo_inner(&buf)
}

pub fn decrypt_biovideo(file_content: [u8; 0x20000]) -> BiovideoEncryptionFiles {
    let mut crypt_result = crypt_biovideo_inner(&file_content);

    let bio2base = crypt_result.to_owned();

    apply_xor_layer(&mut crypt_result);

    let firmware: [u8; 0x10000] = crypt_result[0x10000..0x20000]
        .try_into()
        .expect("Firmware part of decrypted content should be exactly 0x10000 bytes");

    BiovideoEncryptionFiles { bio2base, firmware }
}

fn crypt_16_bytes(input: &[u8; 16]) -> [u8; 16] {
    let mut result = xor_with_array(input, 0);

    for i in 1..11 {
        result = substitute_bytes(&result);
        result = shift_rows(&result);
        if i != 10 {
            result = mix_columns(&result);
        }
        result = xor_with_array(&result, 8 * i);
    }

    result
}

